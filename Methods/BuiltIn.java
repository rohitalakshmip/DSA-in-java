package Methods;

public class BuiltIn {
    public static void main(String[] args) {
        // Math. Function
        System.out.println(Math.sqrt(4));   // squre root
        System.out.println(Math.cbrt(100)); // cube root
        System.out.println(Math.PI);
        System.out.println(Math.abs(-345)); //absolute or modulus
        System.out.println(Math.floor(-7.8)); // Greater integer function
        System.out.println(Math.floor(3.8));
        System.out.println(Math.ceil(-7.8));  // lowest integer function
        System.out.println(Math.ceil(3.55));
        System.out.println(Math.min(3,-1));  // Minimum of two numbers
        System.out.println(Math.max(3,-1));  //Maximum of two number
        System.out.println(Math.pow(5,3));   //power
    }
}
